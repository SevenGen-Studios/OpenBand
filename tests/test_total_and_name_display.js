const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('assets/openband.js','utf8');
const names=['parseMoney','formatMoney','money','roleOf','cleanPeople','calculateRowTotal','rowExpenseTravel','rowOther','sumRows','renderT'];
const functions=source.split('\n').filter(l=>names.some(n=>l.startsWith(`function ${n}(`))).join('\n');
const nodes={tb:{},tfl:{},tft:{}};
const context=vm.createContext({raw:(p,k)=>p[k]??null,el:id=>nodes[id],esc:String,visibleRows:()=>context.rows});
vm.runInContext(functions,context);
const original={name:'Deborah Houle',role:'Councillor',months:12,remuneration:null,travel:null,otherPayments:null,total:null,sourceAllAmountsUnreported:true};
const anonymous={name:null,sourceNameOmitted:true,sourceRowNumber:1,role:'Chief',remuneration:375000,travel:145208,otherPayments:76100,total:596308};
context.rows=context.cleanPeople({people:[original,anonymous]});
assert.equal(context.rows[1].name,'');
assert.equal(context.rows[0].remuneration,null);assert.equal(context.rows[0].otherPayments,null);assert.equal(context.rows[0].total,null);
context.renderT();
const first=nodes.tb.innerHTML.split('</tr>')[0];
assert.match(first,/data-label="Total" class="amtt">\$0<\/td>/);
assert.match(first,/data-label="Remuneration" class="amt">&mdash;<\/td>/);
assert.match(first,/data-label="Other" class="amt">&mdash;<\/td>/);
assert.match(nodes.tb.innerHTML,/<div class="tn"><\/div>/);
assert.ok(!nodes.tb.innerHTML.includes('Name not disclosed'));
assert.ok(!nodes.tb.innerHTML.includes('Not reported'));
assert.equal(original.total,null);assert.equal(anonymous.name,null);
console.log('Missing Total displays $0; missing components and names remain null/blank.');
